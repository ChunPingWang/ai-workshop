    MERCHANT_ID     VARCHAR2(10) NOT NULL,
    TOS_VERSION     NUMBER(8,0) DEFAULT 1 NOT NULL,
    TOS_URL         VARCHAR2(256) NOT NULL,
    TOS_CONTENT     CLOB NOT NULL,
    TOS_NOTE        VARCHAR2(1024),
    TOS_MODIFIED_DATE VARCHAR2(14) NOT NULL,
    TOS_START_DATE  VARCHAR2(14) NOT NULL
);

