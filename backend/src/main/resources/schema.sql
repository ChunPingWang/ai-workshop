-- new-pay OnlineStore(GPS) schema, 依 SD 4.7 Schema調整
-- H2 MODE=Oracle

-- 4.7.1 MWP_SMS_GPS
CREATE TABLE MWP_SMS_GPS (
    ID                  VARCHAR2(20) NOT NULL,
    CREATE_TIME         VARCHAR2(14) NOT NULL,
    SOURCE_SMS_CONTENT  VARCHAR2(128) NOT NULL,
    SOURCE_MSISDN       VARCHAR2(20) NOT NULL,
    REQ_CONTENT         VARCHAR2(128),
    STATUS              VARCHAR2(2) NOT NULL,       -- D:Done F:fail
    REQ_TIME            VARCHAR2(21),
    RET_CODE            VARCHAR2(16),
    RET_DESCRIPTION     VARCHAR2(128),
    PRIMARY KEY (ID)
);

-- 4.7.2 MWP_GPS_SOAP_PROVISIONING
CREATE TABLE MWP_GPS_SOAP_PROVISIONING (
    ID              VARCHAR2(32) NOT NULL,
    CREATE_TIME     VARCHAR2(14) NOT NULL,
    REQUEST_XML     VARCHAR2(256) NOT NULL,     -- spec 就是 256, XML 存不下, 程式先截斷處理
    CORRELATION_ID  VARCHAR2(20) NOT NULL,
    OUT             VARCHAR2(20) NOT NULL,
    PROV_RESULT     VARCHAR2(20),
    IS_PROVISIONED  VARCHAR2(20),
    RESP_XML        VARCHAR2(256),
    PRIMARY KEY (ID)
);

-- 4.7.3 MWP_GPS_SOAP_AUTH
CREATE TABLE MWP_GPS_SOAP_AUTH (
    ID                  VARCHAR2(32) NOT NULL,
    CREATE_TIME         VARCHAR2(14) NOT NULL,
    REQUEST_XML         VARCHAR2(256) NOT NULL,
    CORRELATION_ID      VARCHAR2(20) NOT NULL,
    PURCHASE_TIME       VARCHAR2(21) NOT NULL,
    OUT                 VARCHAR2(20) NOT NULL,
    PAYMENT_DESCRIPTION VARCHAR2(128) NOT NULL,
    MERCHANT_CONTACT    VARCHAR2(128) NOT NULL,
    PRICE               VARCHAR2(21) NOT NULL,
    ROUNDED_PRICE       NUMBER(8,0) NOT NULL,
    AUTH_RESULT         VARCHAR2(20),
    AUTH_TXID           VARCHAR2(20),
    RESP_XML            VARCHAR2(256),
    PRIMARY KEY (ID)
);

-- 4.7.4 MWP_GPS_REQ_LOG
CREATE TABLE MWP_GPS_REQ_LOG (
    REQ_ID          VARCHAR2(32) NOT NULL,
    CREATE_TIME     VARCHAR2(14) NOT NULL,
    FILE_NAME       VARCHAR2(80) NOT NULL,      -- spec 寫 20 但檔名根本放不下, 先改 80
    STATUS          VARCHAR2(2) NOT NULL,       -- I/P/PD/F/D
    RESP_TIME       VARCHAR2(14),
    RESP_FILE_NAME  VARCHAR2(80),
    LAST_MOD_TIME   VARCHAR2(14) NOT NULL,
    PRIMARY KEY (REQ_ID)
);

-- 4.7.5 MWP_GPS_REQ_DETAIL (spec 說 REQ_ID 是 pKey 但一個檔有多筆明細, 所以沒放 PK)
CREATE TABLE MWP_GPS_REQ_DETAIL (
    REQ_ID              VARCHAR2(32) NOT NULL,
    REQ_TYPE            VARCHAR2(128) NOT NULL,
    REQ_TIMESTAMP       VARCHAR2(21) NOT NULL,
    CORRELATION_ID      VARCHAR2(64) NOT NULL,
    BILLING_AGREEMENT_ID VARCHAR2(64) NOT NULL,
    RESP_TIMESTAMP      VARCHAR2(21),
    RESULT_CODE         VARCHAR2(128),
    MESSAGE             VARCHAR2(1024)
);
CREATE INDEX IDX_GPS_REQ_ORDERNO_TYPE ON MWP_GPS_REQ_DETAIL (CORRELATION_ID, REQ_TYPE);

-- 4.7.6 MWP_CP_RECON_DAILY_LOG
